/*
 * Python-free C ABI for the reggression Haskell core.
 *
 * The Haskell modules imported by the `reggression_capi` foreign-library
 * target reference two C symbols for diagnostic output
 * (`unsafe_py_write_stdout` / `unsafe_py_write_stderr`).  The Python/SWIG
 * target implements them with the CPython C API; this shim implements the
 * same symbols with plain stdio so the library can be loaded from any host
 * (Julia, C, ...) without linking libpython.
 *
 * The exported `reggression_*` functions are the stable host-facing ABI.
 * `reggression_run` returns a malloc'd NUL-terminated string; release it with
 * `reggression_free`.
 */

#include <stdio.h>
#include <stdlib.h>

/* Symbols imported by src/Reggression.hs. */
void unsafe_py_write_stdout(char *s) {
  fputs(s, stdout);
  fflush(stdout);
}

void unsafe_py_write_stderr(char *s) {
  fputs(s, stderr);
  fflush(stderr);
}

/* GHC RTS entry points.  Declared manually so this shim does not need the
   GHC RtsAPI.h header on the include path. */
extern void hs_init_with_rtsopts(int *argc, char **argv[]);
extern void hs_exit(void);

/* Generated by `foreign export ccall` in src/Reggression.hs. */
extern char *hs_reggression_version(void);
extern char *hs_reggression_run_safe(
    char *myCmd, char *dataset, char *testData, char *loss,
    char *loadFrom, char *dumpTo, char *parseCSV,
    int parseParams, int calcDL, int calcFit, char *varnames,
    int *status);

int reggression_init(int argc, char **argv) {
  hs_init_with_rtsopts(&argc, &argv);
  return 0;
}

void reggression_exit(void) {
  hs_exit();
}

/* Returns a malloc'd string owned by the caller (free with
   reggression_free), or NULL if the Haskell runtime cannot allocate. */
const char *reggression_version(void) {
  return hs_reggression_version();
}

/* status is set to 0 on success and 1 when the command raised an uncaught
   Haskell exception.  In both cases the return value is a malloc'd string
   (the command result, or the exception text). */
char *reggression_run(
    char *cmd, char *dataset, char *test, char *loss,
    char *load_from, char *dump_to, char *parse_csv,
    int parse_params, int calc_dl, int calc_fit, char *varnames,
    int *status) {
  return hs_reggression_run_safe(cmd, dataset, test, loss, load_from, dump_to,
                                 parse_csv, parse_params, calc_dl, calc_fit,
                                 varnames, status);
}

void reggression_free(char *s) {
  free(s);
}
